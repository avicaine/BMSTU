// vector.h - заголовочный файл класса Vector.
// Лабораторная работа №3, часть 1, вариант 8.
// Индивидуальная операция: * (умножение вектора на число), тип элементов - double.
#ifndef VECTOR_H
#define VECTOR_H

#include <iostream>

class Vector // Класс-вектор: динамический массив из double
{
    double *p = nullptr; // Указатель на динамический массив, задающий вектор
    int n = 0;           // Число элементов (размерность) вектора

    // Закрытый вспомогательный конструктор: выделяет память под n элементов
    // без инициализации. Нужен только операции *, чтобы создать вектор-результат.
    explicit Vector(int n);

public:
    Vector();                            // Конструктор без параметров: пустой вектор (n = 0)
    Vector(const double *arr, int size); // Конструктор на основе обычного массива
    Vector(const Vector &V);             // Конструктор копирования
    Vector(Vector &&V) noexcept;         // Конструктор перемещения
    ~Vector();                           // Деструктор

    double &operator[](int index);               // Операция []: обращение к элементу
    Vector &operator=(const Vector &v2);         // Операция =: присваивание с копированием
    Vector &operator=(Vector &&v2) noexcept;     // Операция =: присваивание с перемещением

    // Индивидуальная операция варианта 8: вектор * число.
    // Первый операнд - объект класса, поэтому операция - функция класса
    // с одним параметром (второй операнд). Объект не меняется (const).
    Vector operator*(double x) const;

    // << и >> не могут быть функциями класса (первый операнд - поток),
    // поэтому они определены вне класса и объявлены дружественными
    friend std::ostream &operator<<(std::ostream &os, const Vector &V);
    friend std::istream &operator>>(std::istream &is, Vector &V);
};

#endif // VECTOR_H
